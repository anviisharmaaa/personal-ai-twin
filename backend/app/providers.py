CHAT_PROVIDERS = ("nvidia", "ollama", "mock")


_LOOPBACK_NAMES = frozenset(("localhost", "127.0.0.1", "::1"))


def ollama_is_local(base_url: str) -> bool:
    """True only for an http(s) URL with no credentials whose host is this machine (localhost or a loopback IP)."""
    try:
        parts = urlsplit(base_url.strip())
        host = (parts.hostname or "").lower()
        if parts.scheme not in ("http", "https") or parts.username or parts.password or not host:
            return False
        if host in _LOOPBACK_NAMES:
            return True
        return ipaddress.ip_address(host).is_loopback
    except ValueError:
        return False


def ollama_endpoint_ok(s: Settings) -> bool:
    """Ollama may only be used at a loopback address unless the operator deliberately sets OLLAMA_ALLOW_REMOTE."""
    url = s.ollama_base_url.strip()
    if ollama_is_local(url):
        return True
    parts = urlsplit(url)
    return bool(s.ollama_allow_remote and parts.scheme in ("http", "https") and parts.hostname
                and not parts.username and not parts.password)


def active_provider(s: Settings) -> str:
    """The configured provider id, or "" when none/unknown. "mock" is refused in production."""
    p = s.ai_provider.strip().lower()
    if p not in PROVIDERS or (p == "mock" and s.app_env.lower() == "production"):
        return ""
    return p


def active_chat_provider(s: Settings) -> str:
    """The configured chat provider id, or "" when chat is off/unknown. "mock" is refused in production."""
    p = s.chat_provider.strip().lower()
    if p not in CHAT_PROVIDERS or (p == "mock" and s.app_env.lower() == "production"):
        return ""
    return p


def consent_version(s: Settings) -> str:
    """Consent is tied to the providers: changing either provider changes the version, so users must re-consent.
    Chat adds its own suffix because chat content (messages, character description, saved gender/pronouns, approved
    memories) goes to the chat provider, which is a different disclosure from character analysis."""
    p = active_provider(s) or "none"
    if p == "ollama" and not ollama_is_local(s.ollama_base_url):
        p = "ollama-remote"  # different disclosure (the text leaves this machine), so a different agreement
    c = active_chat_provider(s)
    if c == "ollama" and not ollama_is_local(s.ollama_base_url):
        c = "ollama-remote"
    return f"{CONSENT_BASE}-{p}" + (f"-chat-{c}" if c else "")


