def _log_timing(provider: Any, state: str, failure: str | None, meta: Any, ctx: Any) -> None:
    """One diagnostics line per reply: numbers and settings only, never message text, names or secrets."""
    summary: dict[str, Any] = getattr(provider, "settings_summary", dict)()
    log.info("chat_timing provider=%s model=%s status=%s failure=%s first_token_ms=%s total_ms=%s load_ms=%s "
             "prompt_eval_ms=%s eval_ms=%s prompt_tokens=%s output_tokens=%s thinking_chars=%s history_turns=%s/%s "
             "settings=%s", provider.provider, getattr(provider, "model", "-"), state, failure or "-",
             meta.first_token_ms, meta.duration_ms, meta.load_ms, meta.prompt_eval_ms, meta.eval_ms,
             meta.prompt_tokens, meta.completion_tokens, meta.thinking_chars, ctx.used_turns, ctx.total_turns,
             summary)

# Conversations with a reply being generated in THIS process. A message row still marked "streaming" that is not in
# here belongs to a process that died, and is shown as incomplete.
_streaming: set[str] = set()
_UUID = re.compile(r"^[A-Za-z0-9_-]{1,64}$")  # no PostgREST filter metacharacters can pass


def get_chat_provider() -> ChatProvider | UnavailableChat:
    return build_chat_provider(get_settings())


def _err(code: str, message: str, http: int) -> HTTPException:
    return HTTPException(http, {"code": code, "message": message})


class ConversationIn(BaseModel):
    title: str | None = Field(default=None, max_length=120)
    character_id: str | None = Field(default=None, max_length=64)   # a request only: verified against the owner


class MessageIn(BaseModel):
    content: str = Field(min_length=1)
    client_message_id: str = Field(min_length=8, max_length=64, pattern=r"^[A-Za-z0-9_-]+$")

    @field_validator("content")
    @classmethod
    def _not_blank(cls, v: str) -> str:
        if not v.strip():
            raise ValueError("Write a message first.")
        return v


def _profile_state(twin: dict[str, Any] | None, row: dict[str, Any] | None) -> str:
    if not row or row.get("profile") is None:
        return "missing"
    return "current" if twin and row.get("description_version") == twin.get("character_version") else "outdated"


def _public_conversation(c: dict[str, Any]) -> dict[str, Any]:
    out = {k: c.get(k) for k in ("id", "title", "created_at", "last_activity_at", "archived_at",
                                 "learning_reviewed_at", "learning_failure_code")}
    out["character_id"] = c.get("twin_id")
    return out


def _public_message(m: dict[str, Any]) -> dict[str, Any]:
    return {k: m.get(k) for k in ("id", "role", "content", "status", "reply_to", "provider", "model", "first_token_ms",
                                  "duration_ms", "failure_code", "used_memory_ids", "created_at", "client_message_id")}


async def _conversation(rest: SupabaseRest, user: AuthUser, cid: str) -> dict[str, Any]:
    """Ownership is checked here in the query AND by RLS. A guessed id of someone else's conversation is a 404."""
    if not _UUID.match(cid):
        raise _err("not_found", "That conversation doesn't exist.", status.HTTP_404_NOT_FOUND)
    rows = await rest.select(user.token, "conversations",
                             {"select": "*", "id": _eq(cid), "owner_id": _eq(user.id)})
    if not rows:
        raise _err("not_found", "That conversation doesn't exist.", status.HTTP_404_NOT_FOUND)
    return rows[0]


async def _owned_character(rest: SupabaseRest, user: AuthUser, character_id: str) -> dict[str, Any]:
    return await owned_character(rest, user, character_id)


async def _conversation_character(rest: SupabaseRest, user: AuthUser, conv: dict[str, Any]) -> dict[str, Any]:
    """The character a conversation is bound to: read from the conversation row itself, never from the request."""
    return await _owned_character(rest, user, str(conv.get("twin_id") or ""))


@router.get("/characters")
async def list_characters(user: AuthUser = Depends(current_user), rest: SupabaseRest = Depends(get_rest),
                          ) -> dict[str, Any]:
    """The user's own characters for the picker. Today an account has one; the shape is a list on purpose."""
    twins = await rest.select(user.token, "twins", {"select": "*", "owner_id": _eq(user.id), "order": "created_at.asc"})
    convs = await rest.select(user.token, "conversations", {
        "select": "id,twin_id,last_activity_at", "owner_id": _eq(user.id), "archived_at": "is.null", "limit": "1000"})
    out = []
    for t in twins:
        mine = [c for c in convs if c.get("twin_id") == t["id"]]
        row = await get_profile_row(rest, user, t["id"])
        desc = " ".join((t.get("character_description") or "").split())
        portrait = await _with_portrait_url(rest, user, t)
        out.append({
            "id": t["id"], "name": t.get("name") or "", "is_self": t.get("kind") == "self",
            "portrait_url": portrait.get("portrait_url"),
            "summary": desc[:200] + ("…" if len(desc) > 200 else ""),
            "has_description": bool(desc), "profile_state": _profile_state(t, row),
            "conversation_count": len(mine),
            "last_activity_at": max((c.get("last_activity_at") or "" for c in mine), default=None),
        })
    return {"characters": out}


async def _user_identity(rest: SupabaseRest, user: AuthUser) -> UserIdentity:
    rows = await rest.select(user.token, "profiles", {"select": "*", "id": _eq(user.id), "limit": "1"})
    return user_identity_of(rows[0] if rows else None)


@router.get("/chat/status")
async def chat_status(character_id: str | None = Query(default=None, max_length=64),
                      user: AuthUser = Depends(current_user), rest: SupabaseRest = Depends(get_rest),
                      provider: ChatProvider | UnavailableChat = Depends(get_chat_provider)) -> dict[str, Any]:
    """Why chat can or cannot be used right now, so the page can explain instead of failing on send."""
    s = get_settings()
    twin = await _owned_character(rest, user, character_id) if character_id else await _twin(rest, user)
    consent = await _active_consent(rest, user)
    row = await get_profile_row(rest, user, twin["id"]) if twin else None
    has_description = bool(twin and (twin.get("character_description") or "").strip())
    reason: str | None = None
    if twin is None:
        reason = "no_twin"
    elif not provider.configured:
        reason = provider.code if isinstance(provider, UnavailableChat) else "not_configured"
    elif not s.ai_enabled:
        reason = "ai_disabled"
    elif consent is None or consent.get("version") != consent_version(s):
        reason = "consent_required"
    elif not has_description:
        reason = "no_character"      # the description is the character; a generated profile is optional
    return {
        "available": reason is None, "reason": reason, "character_id": twin["id"] if twin else None,
        "provider": provider.provider,
        "is_sample": provider.provider == "mock",
        "model_busy": bool(getattr(provider, "exclusive", False)) and model_gate.busy,
        "profile_state": _profile_state(twin, row),
        "profile_outdated": _profile_state(twin, row) == "outdated",
        "user_identity_set": (await _user_identity(rest, user)).stated,
        "identity": ({"gender": identity_of(twin).gender, "pronouns": identity_of(twin).pronouns} if twin else None),
        "limits": {"max_user_chars": s.chat_max_user_chars, "context_messages": s.chat_context_messages},
    }


@router.get("/conversations")
async def list_conversations(character_id: str | None = Query(default=None, max_length=64),
                             user: AuthUser = Depends(current_user), rest: SupabaseRest = Depends(get_rest),
                             ) -> dict[str, Any]:
    query = {"select": "*", "owner_id": _eq(user.id), "archived_at": "is.null", "order": "last_activity_at.desc",
             "limit": "100"}
    if character_id:
        query["twin_id"] = _eq((await _owned_character(rest, user, character_id))["id"])
    rows = await rest.select(user.token, "conversations", query)
    return {"conversations": [_public_conversation(r) for r in rows]}


@router.post("/conversations", status_code=status.HTTP_201_CREATED)
async def create_conversation(body: ConversationIn, user: AuthUser = Depends(current_user),
                              rest: SupabaseRest = Depends(get_rest)) -> dict[str, Any]:
    if body.character_id:
        twin: dict[str, Any] | None = await _owned_character(rest, user, body.character_id)
    else:       # no character named: fine while the account has exactly one, ambiguous otherwise
        owned = await rest.select(user.token, "twins", {"select": "*", "owner_id": _eq(user.id), "limit": "2"})
        if len(owned) > 1:
            raise _err("character_required", "Choose which character to talk to.", status.HTTP_422_UNPROCESSABLE_ENTITY)
        twin = owned[0] if owned else None
    if twin is None:
        raise _err("no_twin", "Create your twin's identity first.", status.HTTP_409_CONFLICT)
    row = await rest.insert(user.token, "conversations", {
        "owner_id": user.id, "twin_id": twin["id"], "title": (body.title or "New conversation").strip()[:120] or
        "New conversation"})
    return _public_conversation(row)


@router.patch("/conversations/{cid}")
async def rename_conversation(cid: str, body: ConversationIn, user: AuthUser = Depends(current_user),
                              rest: SupabaseRest = Depends(get_rest)) -> dict[str, Any]:
    await _conversation(rest, user, cid)
    title = (body.title or "").strip()
    if not title:
        raise _err("invalid_title", "Give the conversation a name.", status.HTTP_422_UNPROCESSABLE_ENTITY)
    rows = await rest.update(user.token, "conversations", {"id": _eq(cid), "owner_id": _eq(user.id)}, {"title": title})
    return _public_conversation(rows[0])


async def _reconcile(rest: SupabaseRest, user: AuthUser, cid: str, rows: list[dict[str, Any]]) -> None:
    """A row still "streaming" that this process is not generating was cut off by a restart or crash: mark it
    incomplete so the page never shows an endlessly running reply."""
    if cid in _streaming:
        return
    for m in rows:
        if m.get("status") == "streaming":
            await rest.update(user.token, "messages", {"id": _eq(m["id"]), "owner_id": _eq(user.id)},
                              {"status": "incomplete", "failure_code": "interrupted"})
            m["status"], m["failure_code"] = "incomplete", "interrupted"


@router.get("/conversations/{cid}/messages")
async def list_messages(cid: str, user: AuthUser = Depends(current_user), rest: SupabaseRest = Depends(get_rest),
                        ) -> dict[str, Any]:
    conv = await _conversation(rest, user, cid)
    rows = await rest.select(user.token, "messages", {
        "select": "*", "conversation_id": _eq(cid), "owner_id": _eq(user.id), "order": "created_at.asc",
        "limit": "500"})
    await _reconcile(rest, user, cid, rows)
    return {"conversation": _public_conversation(conv), "messages": [_public_message(m) for m in rows],
            "generating": cid in _streaming}


@router.delete("/conversations/{cid}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_conversation(cid: str, delete_memories: bool = Query(default=False),
                              user: AuthUser = Depends(current_user), rest: SupabaseRest = Depends(get_rest)) -> None:
    """Deleting a conversation deletes its messages and any UNREVIEWED learning candidates from it. Memories the user
    already approved are kept (they were the user's own decision) unless `delete_memories=true`; kept memories lose
    the quotes copied from the deleted messages and are marked as having no surviving source."""
    await _conversation(rest, user, cid)
    if cid in _streaming:
        raise _err("in_progress", "A reply is being written. Stop it first.", status.HTTP_409_CONFLICT)
    own = {"owner_id": _eq(user.id), "conversation_id": _eq(cid)}
    await rest.delete(user.token, "memory_candidates", {**own, "status": "eq.pending"})
    # Rejected candidates keep only their fingerprint (so a rejected idea does not return); drop the link to the chat.
    if delete_memories:
        await rest.delete(user.token, "memories", own)
    else:
        await rest.update(user.token, "memories", own, {"source_deleted": True, "supporting": [],
                                                        "updated_at": datetime.now(timezone.utc).isoformat()})
    await rest.delete(user.token, "conversations", {"id": _eq(cid), "owner_id": _eq(user.id)})


async def _active_memories(rest: SupabaseRest, user: AuthUser, twin_id: str) -> list[dict[str, Any]]:
    return await rest.select(user.token, "memories", {
        "select": "*", "owner_id": _eq(user.id), "twin_id": _eq(twin_id), "status": "eq.active",
        "order": "created_at.desc", "limit": "200"})


async def _finalize(rest: SupabaseRest, user: AuthUser, cid: str, mid: str, *, content: str, state: str,
                    failure: str | None, meta: StreamMeta, used: list[str]) -> None:
    fields: dict[str, Any] = {"content": content[:20000], "status": state, "failure_code": failure,
                              "first_token_ms": meta.first_token_ms, "duration_ms": meta.duration_ms,
                              "used_memory_ids": used}
    await rest.update(user.token, "messages", {"id": _eq(mid), "owner_id": _eq(user.id)}, fields)
    await rest.update(user.token, "conversations", {"id": _eq(cid), "owner_id": _eq(user.id)},
                      {"last_activity_at": datetime.now(timezone.utc).isoformat()})


@router.post("/conversations/{cid}/messages/stream")
async def stream_message(cid: str, body: MessageIn, user: AuthUser = Depends(current_user),
                         rest: SupabaseRest = Depends(get_rest),
                         provider: ChatProvider | UnavailableChat = Depends(get_chat_provider)) -> StreamingResponse:
    s = get_settings()
    conv = await _conversation(rest, user, cid)
    if len(body.content) > s.chat_max_user_chars:
        raise _err("too_long", f"Keep a message under {s.chat_max_user_chars} characters.",
                   status.HTTP_422_UNPROCESSABLE_ENTITY)
    twin = await _conversation_character(rest, user, conv)     # the character is the conversation's, not the request's

    consent = await _active_consent(rest, user)
    if consent is None or consent.get("version") != consent_version(s):
        raise _err("consent_required", "Please accept AI processing in Settings before chatting.",
                   status.HTTP_403_FORBIDDEN)
    if not s.ai_enabled:
        raise _err("ai_disabled", "AI is temporarily switched off.", status.HTTP_503_SERVICE_UNAVAILABLE)
    if isinstance(provider, UnavailableChat) or not provider.configured:
        code = provider.code if isinstance(provider, UnavailableChat) else "not_configured"
        msg = provider.message if isinstance(provider, UnavailableChat) else "Chat isn't set up on the server yet."
        raise _err(code, msg, status.HTTP_503_SERVICE_UNAVAILABLE)
    description = (twin.get("character_description") or "").strip()
    if not description:
        raise _err("no_character", "Describe your character first: every reply is guided by that description.",
                   status.HTTP_409_CONFLICT)
    row = await get_profile_row(rest, user, twin["id"])      # optional, supplementary guidance
    pstate = _profile_state(twin, row)

    since = (datetime.now(timezone.utc) - timedelta(hours=1)).isoformat()
    recent = await rest.select(user.token, "messages", {
        "select": "id", "owner_id": _eq(user.id), "role": "eq.user", "created_at": f"gte.{since}",
        "limit": str(s.chat_messages_per_hour + 1)})
    if len(recent) >= s.chat_messages_per_hour:
        raise _err("rate_limited", "You've sent a lot of messages this hour. Please try again later.",
                   status.HTTP_429_TOO_MANY_REQUESTS)

    if cid in _streaming:
        raise _err("in_progress", "A reply is already being written in this conversation.", status.HTTP_409_CONFLICT)

    history = await rest.select(user.token, "messages", {
        "select": "*", "conversation_id": _eq(cid), "owner_id": _eq(user.id), "order": "created_at.asc",
        "limit": "500"})
    await _reconcile(rest, user, cid, history)

    # ---- idempotency: the same client_message_id is the same user message, whatever happens to the reply ----
    existing = next((m for m in history
                     if m["role"] == "user" and m.get("client_message_id") == body.client_message_id), None)
    if existing is not None:
        replies = [m for m in history if m["role"] == "assistant" and m.get("reply_to") == existing["id"]]
        done = next((m for m in replies if m["status"] == "complete"), None)
        if done is not None:
            return _replay(existing, done)
        for stale in replies:      # a failed / cancelled / incomplete attempt is replaced, never duplicated
            await rest.delete(user.token, "messages", {"id": _eq(stale["id"]), "owner_id": _eq(user.id)})
        history = [m for m in history if m["id"] not in {r["id"] for r in replies}]
        user_row = existing
        history = [m for m in history if m["id"] != existing["id"]]
    else:
        user_row = None

    uses_gate = bool(getattr(provider, "exclusive", False))   # only a local model needs the one-at-a-time slot
    if uses_gate and model_gate.busy:     # a quick refusal; the real slot is taken when the stream starts (below)
        raise _err("model_busy", "The local model is busy with another task. Try again in a moment.",
                   status.HTTP_429_TOO_MANY_REQUESTS)
    profile = row["profile"] if row and pstate != "missing" else None
    memories = await _active_memories(rest, user, twin["id"])
    recent_user = [m["content"] for m in history if m["role"] == "user"][-1:]
    chosen = rank_memories(memories, body.content + " " + " ".join(recent_user), s.chat_memory_limit)
    idn = identity_of(twin)        # from the record the conversation is bound to, never from the request
    if description_conflicts(idn, description):
        log.warning("identity_conflict: selected gender and description wording differ; the selection governs")
    # The USER's saved identity: read with THEIR token from THEIR profile row (RLS); the request has no such field.
    sys_text = system_prompt(twin.get("name") or "", profile, description, chosen,
                             profile_outdated=pstate == "outdated", identity=idn,
                             user=await _user_identity(rest, user))
    ctx = build_context(sys_text, history, body.content, max_messages=s.chat_context_messages,
                        max_chars=s.chat_context_chars)

    if user_row is None:
        try:
            user_row = await rest.insert(user.token, "messages", {
                "conversation_id": cid, "owner_id": user.id, "role": "user", "content": body.content,
                "status": "complete", "client_message_id": body.client_message_id})
        except SupabaseError as exc:
            if exc.status_code == 409:      # a parallel identical request won the race
                raise _err("duplicate", "That message was already sent.", status.HTTP_409_CONFLICT) from exc
            raise
        if not history:
            await rest.update(user.token, "conversations", {"id": _eq(cid), "owner_id": _eq(user.id)},
                              {"title": re.sub(r"\s+", " ", body.content).strip()[:60] or conv["title"]})
    mem_ids = [m["id"] for m in chosen]
    asst = await rest.insert(user.token, "messages", {
        "conversation_id": cid, "owner_id": user.id, "role": "assistant", "content": "", "status": "streaming",
        "reply_to": user_row["id"], "provider": provider.provider, "model": provider.model,
        "used_memory_ids": mem_ids})

    started_event = {
        "user_message_id": user_row["id"], "assistant_message_id": asst["id"], "provider": provider.provider,
        "model": provider.model, "is_sample": provider.provider == "mock", "replayed": False,
        "context": {"earlier_messages_used": ctx.used_turns, "earlier_messages_total": ctx.total_turns,
                    "trimmed": ctx.trimmed},
        "profile_state": pstate, "profile_outdated": pstate == "outdated",
        "character": {"id": twin["id"], "name": twin.get("name") or ""},
        "memories_used": [{"id": m["id"], "statement": m["statement"]} for m in chosen],
    }
    hint = looks_like_correction(body.content)

    async def events() -> AsyncIterator[bytes]:
        parts: list[str] = []
        meta = StreamMeta()
        state, failure, err_msg = "complete", None, ""
        t0 = asyncio.get_running_loop().time()
        # The slot and the per-conversation lock are taken HERE, when the stream really starts, so a request that
        # is dropped before it starts can never leave them held.
        busy = ("in_progress" if cid in _streaming
                else ("model_busy" if uses_gate and not model_gate.try_acquire() else None))
        acquired = busy is None
        got_slot = acquired and uses_gate
        if acquired:
            _streaming.add(cid)
        try:
            yield sse("started", started_event)
            if busy:
                msg = ("A reply is already being written in this conversation." if busy == "in_progress"
                       else "The local model is busy with another task. Try again in a moment.")
                await _finalize(rest, user, cid, asst["id"], content="", state="failed", failure=busy, meta=meta,
                                used=[])
                yield sse("error", {"code": busy, "assistant_message_id": asst["id"], "message": msg,
                                    "partial_saved": False})
                return
            try:
                async for kind, val in provider.stream(ctx.messages):
                    if kind == "delta":
                        parts.append(val)
                        yield sse("delta", {"text": val})
                    else:
                        meta = val
                text = "".join(parts)
                if not text.strip():
                    raise ChatError("empty_response", "The model sent back an empty answer.", 502)
                if meta.finish_reason == "length":
                    state, failure = "incomplete", "truncated"
                    err_msg = "The reply reached the length limit and was cut off. Ask for more and I\u2019ll continue."
            except ChatError as exc:
                state, failure, err_msg = "failed", exc.code, exc.message
                log.warning("chat_failed code=%s provider=%s detail=%s", exc.code, provider.provider, exc.detail or "-")
            if meta.duration_ms is None:
                meta.duration_ms = int((asyncio.get_running_loop().time() - t0) * 1000)
            _log_timing(provider, state, failure, meta, ctx)
            try:
                await _finalize(rest, user, cid, asst["id"], content="".join(parts), state=state, failure=failure,
                                meta=meta, used=mem_ids)
            except SupabaseError:
                log.warning("chat_persist_failed provider=%s", provider.provider)
                yield sse("error", {"code": "persist_failed", "assistant_message_id": asst["id"],
                                    "message": "The reply was written but couldn't be saved, so it may be gone after "
                                               "a refresh."})
                return
            if state == "complete":
                yield sse("done", {"assistant_message_id": asst["id"], "status": "complete",
                                   "first_token_ms": meta.first_token_ms, "duration_ms": meta.duration_ms,
                                   "correction_hint": hint})
            else:
                yield sse("error", {"code": failure, "assistant_message_id": asst["id"], "message": err_msg,
                                    "partial_saved": bool(parts)})
        except (asyncio.CancelledError, GeneratorExit):
            # The browser stopped or disconnected. Keep what was written, marked cancelled (never "complete").
            meta.duration_ms = int((asyncio.get_running_loop().time() - t0) * 1000)
            task = asyncio.ensure_future(_finalize(
                rest, user, cid, asst["id"], content="".join(parts), state="cancelled", failure="cancelled",
                meta=meta, used=mem_ids))
            try:
                await asyncio.shield(task)
            except (SupabaseError, asyncio.CancelledError):
                log.warning("chat_cancel_persist_failed")
            raise
        finally:
            if acquired:
                _streaming.discard(cid)
            if got_slot:
                model_gate.release()

    return StreamingResponse(events(), media_type="text/event-stream", headers={
        "Cache-Control": "no-cache, no-transform", "X-Accel-Buffering": "no", "Connection": "keep-alive"})


def _replay(user_row: dict[str, Any], done: dict[str, Any]) -> StreamingResponse:
    """The same message id was already answered: return that stored answer, with no new model call."""
